"""Step 4: RSA (EN vs ES distance correlation) within clusters, between clusters, and among cluster-centre words.

11,128 one-to-one dictionary pairs; labels from the k=12 matched-only clustering of EN (or ES).
  within  : word pairs whose two words share a cluster (pooled, and per cluster)
  between : word pairs whose two words are in different clusters
  centres : the 12 words nearest each cluster centre (in the clustering language), their 66 word pairs
Distances as in step4_local_global.py (GW normalization, mean 1). Spearman and Pearson.
Output: analysis/tables/step4_rsa_clusters_K<K>.md
Usage: poetry run python code/experiments/step4_rsa_clusters.py
"""

from __future__ import annotations

import numpy as np
from scipy.stats import pearsonr, spearmanr
from sklearn.cluster import KMeans

from localgw.data import REPO_ROOT, load_vectors
from localgw.preprocess import normalize_embeddings
from step4_k12_plots import NAMES
from step4_local_global import distances
from step4_plots import DATA, K

MAX_SAMPLE = 2_000_000


def corr(a, b, rng):
    if len(a) > MAX_SAMPLE:
        s = rng.choice(len(a), MAX_SAMPLE, replace=False)
        a, b = a[s], b[s]
    return spearmanr(a, b)[0], pearsonr(a, b)[0]


def main() -> None:
    rng = np.random.default_rng(0)
    d = np.load(DATA / f"k12_K{K}.npz")
    pairs = d["pairs"]
    n = len(pairs)
    dist = {"en": distances("en", pairs[:, 0]), "es": distances("es", pairs[:, 1])}
    iu = np.triu_indices(n, 1)
    a, b = dist["en"][iu], dist["es"][iu]

    lines = [f"# RSA within / between clusters and among cluster-centre words ({n} matched pairs, k=12)", "",
             "Generated by `code/experiments/step4_rsa_clusters.py`. RSA = correlation of d_EN and d_ES over word pairs.", ""]
    for li, lang in enumerate(["en", "es"]):
        labels = d[f"{lang}_matched_labels"]
        # recover the cluster centres (same k-means call as step4_k12.py) and check the labels agree
        x = normalize_embeddings(load_vectors(lang, K)[1][pairs[:, li]])
        km = KMeans(12, n_init=10, random_state=0).fit(x)
        order = np.argsort([np.median(pairs[km.labels_ == c, li]) for c in range(12)])
        remap = np.empty(12, int)
        remap[order] = np.arange(12)
        assert (remap[km.labels_] == labels).all()
        centres = km.cluster_centers_[order]
        centre_words = [int(np.flatnonzero(labels == c)[np.argmax(x[labels == c] @ centres[c])]) for c in range(12)]

        same = labels[iu[0]] == labels[iu[1]]
        rw, rb = corr(a[same], b[same], rng), corr(a[~same], b[~same], rng)
        cu = np.triu_indices(12, 1)
        ca = dist["en"][np.ix_(centre_words, centre_words)][cu]
        cb = dist["es"][np.ix_(centre_words, centre_words)][cu]
        rc = (spearmanr(ca, cb)[0], pearsonr(ca, cb)[0])
        lines += [f"## Labels: {lang.upper()} clusters", "",
                  "| word pairs | count | Spearman ρ | Pearson r |", "|---|---|---|---|",
                  f"| within clusters | {same.sum():,} | {rw[0]:.3f} | {rw[1]:.3f} |",
                  f"| between clusters | {(~same).sum():,} | {rb[0]:.3f} | {rb[1]:.3f} |",
                  f"| 12 cluster-centre words | 66 | {rc[0]:.3f} | {rc[1]:.3f} |", "",
                  "Centre words (EN / ES): " + ", ".join(
                      f"{d['en_words'][pairs[i, 0]]}/{d['es_words'][pairs[i, 1]]}" for i in centre_words), "",
                  "| cluster | words | within-cluster pairs | Spearman ρ | Pearson r |", "|---|---|---|---|---|"]
        for c in range(12):
            m = (labels[iu[0]] == c) & (labels[iu[1]] == c)
            r = corr(a[m], b[m], rng)
            lines.append(f"| {NAMES[lang, 'matched'][c]} | {(labels == c).sum()} | {m.sum():,} | {r[0]:.3f} | {r[1]:.3f} |")
        lines.append("")
    out = REPO_ROOT / "analysis" / "tables" / f"step4_rsa_clusters_K{K}.md"
    out.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
