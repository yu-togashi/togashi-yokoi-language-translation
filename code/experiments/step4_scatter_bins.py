"""Step 4: correlation of d_EN and d_ES inside 10 equal-width bins of d_EN (all matched word pairs).

Same pairs/distances as step4_scatter.py. For each bin of the EN distance: number of word pairs, mean ES
distance, Spearman ρ and Pearson r of (d_EN, d_ES) within the bin (≤ 300k pairs sampled per bin).
Outputs: analysis/tables/step4_scatter_bins_K<K>.md, analysis/figures/step4_scatter_bins_K<K>.png
Usage: poetry run python code/experiments/step4_scatter_bins.py
"""

from __future__ import annotations

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from scipy.stats import pearsonr, spearmanr  # noqa: E402

from localgw.data import REPO_ROOT  # noqa: E402
from step4_local_global import distances  # noqa: E402
from step4_plots import DATA, FIG, INK, K, MUTED, SLOT, SURFACE, style  # noqa: E402

N_BINS, MAX_SAMPLE = 10, 300_000


def main() -> None:
    rng = np.random.default_rng(0)
    pairs = np.load(DATA / f"k12_K{K}.npz")["pairs"]
    n = len(pairs)
    ds, dt = distances("en", pairs[:, 0]), distances("es", pairs[:, 1])
    iu = np.triu_indices(n, 1)
    a, b = ds[iu], dt[iu]
    del ds, dt
    edges = np.linspace(a.min(), a.max(), N_BINS + 1)
    which = np.clip(np.digitize(a, edges) - 1, 0, N_BINS - 1)
    rows = []
    for j in range(N_BINS):
        m = np.flatnonzero(which == j)
        s = m if len(m) <= MAX_SAMPLE else rng.choice(m, MAX_SAMPLE, replace=False)
        ok = len(s) > 2
        rows.append(dict(lo=edges[j], hi=edges[j + 1], n=len(m), mean_es=b[m].mean() if len(m) else np.nan,
                         rho=spearmanr(a[s], b[s])[0] if ok else np.nan,
                         r=pearsonr(a[s], b[s])[0] if ok else np.nan))
    lines = [f"# Correlation of d_EN and d_ES within equal-width bins of d_EN ({n} matched words, "
             f"{len(a):,} word pairs)", "", "Generated by `code/experiments/step4_scatter_bins.py`.", "",
             "| d_EN bin | word pairs | mean d_ES | Spearman ρ | Pearson r |", "|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['lo']:.2f}–{r['hi']:.2f} | {r['n']:,} | {r['mean_es']:.3f} | {r['rho']:.3f} | {r['r']:.3f} |")
    (REPO_ROOT / "analysis" / "tables" / f"step4_scatter_bins_K{K}.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))

    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(9, 7), sharex=True, facecolor=SURFACE,
                                   gridspec_kw={"height_ratios": [2, 1]})
    centers = [(r["lo"] + r["hi"]) / 2 for r in rows]
    width = edges[1] - edges[0]
    for ax in (ax1, ax2):
        style(ax)
    ax1.plot(centers, [r["rho"] for r in rows], color=SLOT[0], lw=2, marker="o", ms=7, label="Spearman ρ")
    ax1.plot(centers, [r["r"] for r in rows], color=SLOT[1], lw=2, marker="o", ms=7, label="Pearson r")
    ax1.axhline(0, color=MUTED, lw=0.8)
    ax1.set_ylabel("correlation of d_EN and d_ES\nwithin the bin", color=MUTED, fontsize=9)
    ax1.legend(frameon=False, fontsize=9, labelcolor=INK)
    ax1.set_title("Correlation within 10 equal-width bins of the English distance", fontsize=11, color=INK,
                  loc="left")
    ax2.bar(centers, [r["n"] for r in rows], width=width * 0.9, color=SLOT[0])
    ax2.set_yscale("log")
    ax2.set_ylabel("word pairs in bin", color=MUTED, fontsize=9)
    ax2.set_xlabel("distance in English d_EN(i, k)  (mean = 1)", color=MUTED, fontsize=9)
    ax2.set_xticks(edges, [f"{e:.2f}" for e in edges], fontsize=8)
    fig.tight_layout()
    fig.savefig(FIG / f"step4_scatter_bins_K{K}.png", dpi=150, facecolor=SURFACE)


if __name__ == "__main__":
    main()
