"""Step 4 restricted to dictionary-matched words: one-to-one EN–ES pairs inside both top-K.

Pairs: EN top-K words in frequency order; for each, the first MUSE full-dictionary translation that is
in the ES top-K and not used yet (greedy one-to-one). Both sides are then analysed like
step4_structure.py (normalize on the subset, PCA, k-means k=8 ordered by median EN/ES rank), and the
two clusterings are compared through the pairs (ARI, NMI, contingency table).

Outputs: data/processed/step4/matched_K<K>.npz, analysis/tables/step4_matched_K<K>.md
Usage: poetry run python code/experiments/step4_matched.py
"""

from __future__ import annotations

import numpy as np
from sklearn.cluster import KMeans
from sklearn.decomposition import PCA
from sklearn.metrics import adjusted_rand_score, normalized_mutual_info_score, silhouette_score

from localgw.data import REPO_ROOT, load_dictionary, load_vectors
from localgw.preprocess import normalize_embeddings

K, k, SEED = 20000, 8, 0
OUT_DATA = REPO_ROOT / "data" / "processed" / "step4"
OUT_TAB = REPO_ROOT / "analysis" / "tables" / f"step4_matched_K{K}.md"


def matched_pairs(ws, wt, d):
    t_idx = {w: i for i, w in enumerate(wt)}
    used, pairs = set(), []
    for i, w in enumerate(ws):
        for g in d.get(w, []):
            j = t_idx.get(g)
            if j is not None and j not in used:
                used.add(j)
                pairs.append((i, j))
                break
    return np.array(pairs)


def cluster(x, rank):
    km = KMeans(k, n_init=10, random_state=SEED).fit(x)
    order = np.argsort([np.median(rank[km.labels_ == c]) for c in range(k)])
    remap = np.empty(k, int)
    remap[order] = np.arange(k)
    return remap[km.labels_], km.cluster_centers_[order]


def main() -> None:
    rng = np.random.default_rng(SEED)
    ws, xs, _ = load_vectors("en", K)
    wt, xt, _ = load_vectors("es", K)
    pairs = matched_pairs(ws, wt, load_dictionary("en", "es", "full"))
    i, j = pairs.T
    n = len(pairs)
    side = {"en": (np.array(ws)[i], normalize_embeddings(xs[i]), i),
            "es": (np.array(wt)[j], normalize_embeddings(xt[j]), j)}

    res, lines = {}, [f"# Step 4 on dictionary-matched one-to-one pairs (K={K})", "",
                      "Generated by `code/experiments/step4_matched.py`. Greedy one-to-one pairs: EN words in",
                      "frequency order, first MUSE full-dictionary translation inside the ES top-K not used yet.", "",
                      f"- pairs: {n} ({n / K:.0%} of each top-{K}); identical strings: "
                      f"{np.mean(side['en'][0] == side['es'][0]):.0%}", ""]
    sub = rng.choice(n, size=min(5000, n), replace=False)
    for lang, (words, x, rank) in side.items():
        pca = PCA(n_components=50, random_state=SEED).fit(x)
        labels, centers = cluster(x, rank)
        sil = silhouette_score(x[sub], labels[sub])
        dist_in = np.mean([1 - (x[labels == c] @ x[labels == c].T).mean() for c in range(k)])
        dist_all = 1 - x.mean(0) @ x.mean(0)  # mean cosine distance over all pairs = 1 - ||mean||²
        res[lang] = dict(words=words, coords=pca.transform(x)[:, :10], explained=pca.explained_variance_ratio_,
                         labels=labels, rank=rank)
        lines += [f"## {lang}", "",
                  f"PCA PC1–PC5: " + ", ".join(f"{v:.1%}" for v in pca.explained_variance_ratio_[:5])
                  + f"; PC1–PC50 {pca.explained_variance_ratio_.sum():.1%}. Silhouette (k={k}) {sil:.3f}. "
                  f"Mean cosine distance within clusters {dist_in:.3f} vs all pairs {dist_all:.3f} "
                  f"(ratio {dist_in / dist_all:.2f}).", "",
                  "| cluster | size | median rank | most frequent words | words nearest the centre |",
                  "|---|---|---|---|---|"]
        for c in range(k):
            idx = np.flatnonzero(labels == c)
            near = idx[np.argsort(-(x[idx] @ (centers[c] / np.linalg.norm(centers[c]))))[:15]]
            lines.append(f"| {c} | {len(idx)} | {int(np.median(rank[idx]))} | "
                         f"{' '.join(words[idx[:20]])} | {' '.join(words[near])} |")
        lines.append("")

    le, ls = res["en"]["labels"], res["es"]["labels"]
    ct = np.zeros((k, k), int)
    np.add.at(ct, (le, ls), 1)
    lines += ["## EN clusters vs ES clusters (through the pairs)", "",
              f"ARI {adjusted_rand_score(le, ls):.3f}, NMI {normalized_mutual_info_score(le, ls):.3f} "
              f"(random relabelling: ARI ≈ 0)", "",
              "| EN \\ ES | " + " | ".join(f"es{c}" for c in range(k)) + " | best match share |",
              "|---" * (k + 2) + "|"]
    for c in range(k):
        lines.append(f"| en{c} | " + " | ".join(str(v) for v in ct[c]) + f" | {ct[c].max() / ct[c].sum():.0%} |")
    OUT_TAB.write_text("\n".join(lines) + "\n")
    np.savez(OUT_DATA / f"matched_K{K}.npz", pairs=pairs,
             **{f"{lang}_{key}": v for lang, r in res.items() for key, v in r.items()})
    print("\n".join(lines))


if __name__ == "__main__":
    main()
