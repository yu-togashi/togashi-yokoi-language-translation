"""Summarize otalign runs in data/processed/otalign/ into analysis/tables/otalign_runs.{csv,md}.

Per run: K, lambda, threads, iterations, GW solve time, mean time_G per iteration
(iterations 0-99 and 100-199), wall clock, peak RSS, and the six final P@1 values.

Usage: poetry run python code/experiments/summarize_otalign_runs.py
"""

from __future__ import annotations

import re

import numpy as np
import pandas as pd

from localgw.data import REPO_ROOT

RUN_DIR = REPO_ROOT / "data" / "processed" / "otalign"
OUT_DIR = REPO_ROOT / "analysis" / "tables"
SCORES = ["coupling", "coupling_csls", "bary", "bary_csls", "proj", "proj_csls"]
NAME_RE = re.compile(r"(?P<src>\w+)-(?P<trg>\w+)_K(?P<K>\d+)_ereg(?P<ereg>[\de.+-]+?)(?:_t(?P<threads>\d+))?$")


def parse_run(path) -> dict | None:
    m = NAME_RE.match(path.name)
    log = path / "run.log"
    if not m or not log.exists():
        return None
    text = log.read_text(errors="replace")
    row = {"pair": f"{m['src']}-{m['trg']}", "K": int(m["K"]), "lambda": m["ereg"],
           "threads": int(m["threads"] or 16)}

    iters = np.array([[float(x) for x in line.split()]
                      for line in text.splitlines()
                      if re.match(r"^\s+\d+\s", line) and len(line.split()) == 8])
    if len(iters):
        it, time_g = iters[:, 0], iters[:, 6]
        row["iterations"] = int(it.max())
        row["time_G_0-99"] = time_g[it < 100].mean()
        row["time_G_100-199"] = time_g[(it >= 100) & (it < 200)].mean() if (it >= 100).any() else np.nan
        row["final_obj"] = iters[-1, 1]
    if m_solve := re.search(r"Total elapsed time: ([\d.]+)s", text):
        row["gw_solve_s"] = float(m_solve[1])

    p1 = re.findall(r"Accuracy @ 1:\s+([\d.]+)%", text)
    for name, v in zip(SCORES, p1):
        row[f"P@1_{name}"] = float(v)

    tlog = path / "time.log"
    if tlog.exists():
        t = tlog.read_text()
        if m_rss := re.search(r"Maximum resident set size \(kbytes\): (\d+)", t):
            row["peak_rss_GB"] = int(m_rss[1]) / 1024**2
        if m_wall := re.search(r"Elapsed \(wall clock\) time .*: ([\d:.]+)", t):
            parts = [float(x) for x in m_wall[1].split(":")]
            row["wall_min"] = sum(p * 60**i for i, p in enumerate(reversed(parts))) / 60
    return row


def main() -> None:
    rows = [r for p in sorted(RUN_DIR.iterdir()) if p.is_dir() and (r := parse_run(p))]
    df = pd.DataFrame(rows).sort_values(["pair", "K", "lambda", "threads"])
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    df.to_csv(OUT_DIR / "otalign_runs.csv", index=False)
    with open(OUT_DIR / "otalign_runs.md", "w") as f:
        f.write("# otalign runs (Conneau/MUSE, P@1 on train fold within top-K)\n\n"
                "Generated by `code/experiments/summarize_otalign_runs.py`. time_G = gradient + Sinkhorn "
                "per GW iteration [s]. P@1 columns: coupling = argmax of Γ, bary = barycentric projection, "
                "proj = orthogonal map; *_csls = with CSLS.\n\n")
        f.write(df.to_markdown(index=False, floatfmt=".3g"))
        f.write("\n")
    print(df.to_string(index=False))


if __name__ == "__main__":
    main()
