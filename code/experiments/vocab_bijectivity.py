"""How far are the two GW vocabularies (independent top-K per language) from one-to-one?

For each source top-K word, classify by the MUSE full dictionary:
  gold_in_topK     : some gold translation is in the target top-K
  gold_outside_topK: gold translations exist but all lie outside the target top-K
  not_in_dict      : the word has no dictionary entry (function words, punctuation, markup, ...)
Also reports many-to-one: target top-K words that are gold for >1 source top-K word.

Output: analysis/tables/vocab_bijectivity.md
Usage: poetry run python code/experiments/vocab_bijectivity.py
"""

from __future__ import annotations

from collections import Counter

from localgw.data import REPO_ROOT, load_dictionary, load_vocab

PAIRS = [("en", "es"), ("es", "en")]
KS = [2000, 5000, 10000, 20000]
OUT = REPO_ROOT / "analysis" / "tables" / "vocab_bijectivity.md"


def main() -> None:
    vocab = {lang: load_vocab(lang) for lang in ["en", "es"]}
    lines = ["# GW vocabulary (independent top-K) vs one-to-one correspondence\n",
             "Generated by `code/experiments/vocab_bijectivity.py` (MUSE full dictionary).\n",
             "| pair | K | gold in target top-K | gold only outside target top-K | not in dictionary "
             "| target words shared by >1 source word | mean source words per target word |",
             "|---|---|---|---|---|---|---|"]
    for src, trg in PAIRS:
        d = load_dictionary(src, trg, "full")
        for k in KS:
            ws, wt = vocab[src][:k], set(vocab[trg][:k])
            n_in = n_out = n_none = 0
            shared = Counter()
            for w in ws:
                if w not in d:
                    n_none += 1
                    continue
                golds = [g for g in d[w] if g in wt]
                if golds:
                    n_in += 1
                    shared.update(golds)
                else:
                    n_out += 1
            multi = sum(n > 1 for n in shared.values())
            lines.append(f"| {src}-{trg} | {k} | {n_in / k:.1%} | {n_out / k:.1%} | {n_none / k:.1%} "
                         f"| {multi / len(shared):.0%} | {sum(shared.values()) / len(shared):.2f} |")
    OUT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
