"""Step 4: per k-means cluster, how many words have a translation inside the other GW vocabulary.

For each source cluster (MUSE full dictionary, source→target):
  in_other_topK : gold translation present in the target top-K (= has a partner GW could match to)
  outside_topK  : gold translations exist but all lie outside the target top-K
  not_in_dict   : no dictionary entry
  same_theme    : of in_other_topK words, fraction whose translation falls in the target cluster with
                  the same colour/theme (step4_plots.CLUSTERS); the target cluster of the first in-vocab gold is used
Output: analysis/tables/step4_cluster_coverage_K<K>.md
Usage: poetry run python code/experiments/step4_cluster_coverage.py
"""

from __future__ import annotations

import numpy as np

from localgw.data import REPO_ROOT, load_dictionary

from step4_plots import CLUSTERS, DATA, K

OUT = REPO_ROOT / "analysis" / "tables" / f"step4_cluster_coverage_K{K}.md"


def table(src: str, trg: str) -> list[str]:
    s = np.load(DATA / f"{src}_K{K}.npz")
    t = np.load(DATA / f"{trg}_K{K}.npz")
    s_words, s_lab = list(s["words"]), s["labels"]
    t_idx = {w: i for i, w in enumerate(t["words"])}
    t_lab = t["labels"]
    slot_of_t = {c: slot for c, (_, slot) in CLUSTERS[trg].items()}
    d = load_dictionary(src, trg, "full")

    rows = [f"### {src} → {trg}", "",
            "| cluster | size | translation in other top-K | only outside top-K | not in dictionary "
            "| of those in top-K: lands in same-theme cluster |",
            "|---|---|---|---|---|---|"]
    tot = np.zeros(4)
    for c, (name, slot) in sorted(CLUSTERS[src].items(), key=lambda kv: kv[1][1]):
        idx = np.flatnonzero(s_lab == c)
        n_in = n_out = n_none = n_same = 0
        for i in idx:
            golds = d.get(s_words[i])
            if golds is None:
                n_none += 1
                continue
            hits = [t_idx[g] for g in golds if g in t_idx]
            if not hits:
                n_out += 1
                continue
            n_in += 1
            n_same += slot_of_t[t_lab[hits[0]]] == slot
        n = len(idx)
        tot += [n, n_in, n_out, n_none]
        rows.append(f"| {name} | {n} | {n_in / n:.0%} | {n_out / n:.0%} | {n_none / n:.0%} "
                    f"| {n_same / max(n_in, 1):.0%} |")
    rows.append(f"| **all** | {int(tot[0])} | {tot[1] / tot[0]:.0%} | {tot[2] / tot[0]:.0%} "
                f"| {tot[3] / tot[0]:.0%} | |")
    return rows + [""]


def main() -> None:
    lines = [f"# Translation coverage per k-means cluster (K={K}, MUSE full dictionary)", "",
             "Generated by `code/experiments/step4_cluster_coverage.py`.", ""]
    lines += table("en", "es") + table("es", "en")
    OUT.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
