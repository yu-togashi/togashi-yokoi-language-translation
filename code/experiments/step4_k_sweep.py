"""Step 4: choose the number of k-means clusters by consistency, not by eye.

For k in KS, per language (EN, ES), k-means on
  full    : all top-K words (normalized on the full vocabulary)
  matched : only the dictionary-matched one-to-one words (step4_matched.py pairs, normalized on the subset)
and report (ARI / NMI, through the one-to-one pairs or shared words):
  xling_matched : EN matched clusters vs ES matched clusters
  xling_full    : EN full clusters vs ES full clusters, restricted to the pairs
  full_vs_matched_{en,es} : full clusters restricted to matched words vs matched clusters (same language)
  seed_{en,es}  : full clustering with seed 0 vs seed 1 (stability)
  silhouette_{en,es} (full, 5000-word subsample)
Output: analysis/tables/step4_k_sweep_K<K>.md, analysis/figures/step4_k_sweep_K<K>.png
Usage: poetry run python code/experiments/step4_k_sweep.py
"""

from __future__ import annotations

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from sklearn.cluster import KMeans  # noqa: E402
from sklearn.metrics import adjusted_rand_score as ari  # noqa: E402
from sklearn.metrics import normalized_mutual_info_score as nmi  # noqa: E402
from sklearn.metrics import silhouette_score  # noqa: E402

from localgw.data import REPO_ROOT, load_vectors  # noqa: E402
from localgw.preprocess import normalize_embeddings  # noqa: E402
from step4_plots import DATA, FIG, INK, K, MUTED, SLOT, SURFACE, style  # noqa: E402

KS = [6, 8, 10, 12, 14, 16, 20]
OUT_TAB = REPO_ROOT / "analysis" / "tables" / f"step4_k_sweep_K{K}.md"


def km(x, k, seed=0):
    return KMeans(k, n_init=10, random_state=seed).fit_predict(x)


def main() -> None:
    rng = np.random.default_rng(0)
    pairs = np.load(DATA / f"matched_K{K}.npz")["pairs"]
    idx = {"en": pairs[:, 0], "es": pairs[:, 1]}
    full, matched = {}, {}
    for lang in ["en", "es"]:
        _, x, _ = load_vectors(lang, K)
        full[lang] = normalize_embeddings(x)
        matched[lang] = normalize_embeddings(x[idx[lang]])
    sub = rng.choice(K, 5000, replace=False)

    rows = []
    for k in KS:
        lf = {l: km(full[l], k) for l in full}
        lm = {l: km(matched[l], k) for l in matched}
        r = {"k": k}
        for name, a, b in [("xling_matched", lm["en"], lm["es"]),
                           ("xling_full", lf["en"][idx["en"]], lf["es"][idx["es"]]),
                           ("full_vs_matched_en", lf["en"][idx["en"]], lm["en"]),
                           ("full_vs_matched_es", lf["es"][idx["es"]], lm["es"])]:
            r[f"{name}_ARI"], r[f"{name}_NMI"] = ari(a, b), nmi(a, b)
        for l in ["en", "es"]:
            r[f"seed_{l}_ARI"] = ari(lf[l], km(full[l], k, seed=1))
            r[f"silhouette_{l}"] = silhouette_score(full[l][sub], lf[l][sub])
        rows.append(r)
        print({kk: round(v, 3) if isinstance(v, float) else v for kk, v in r.items()}, flush=True)
    df = pd.DataFrame(rows)

    OUT_TAB.write_text(
        f"# Choosing k for k-means on the K={K} vocabularies\n\n"
        "Generated by `code/experiments/step4_k_sweep.py`. ARI (and NMI) between clusterings, compared through the "
        f"{len(pairs)} one-to-one dictionary pairs or the shared words. Random relabelling gives ARI ≈ 0.\n\n"
        + df.to_markdown(index=False, floatfmt=".3f") + "\n")

    fig, ax = plt.subplots(figsize=(9, 5), facecolor=SURFACE)
    style(ax)
    series = [("xling_matched_ARI", "EN↔ES (matched-only clustering)", 0),
              ("xling_full_ARI", "EN↔ES (full clustering, on pairs)", 1),
              ("full_vs_matched_en_ARI", "full vs matched-only, EN", 2),
              ("full_vs_matched_es_ARI", "full vs matched-only, ES", 3),
              ("seed_en_ARI", "seed 0 vs 1, EN (full)", 6),
              ("seed_es_ARI", "seed 0 vs 1, ES (full)", 7)]
    for col, label, slot in series:
        ax.plot(df["k"], df[col], color=SLOT[slot], lw=2, marker="o", ms=6, label=label)
    ax.set_xticks(KS)
    ax.set_xlabel("number of clusters k", color=MUTED, fontsize=9)
    ax.set_ylabel("ARI", color=MUTED, fontsize=9)
    ax.set_ylim(0, 1)
    ax.grid(axis="y", color="#e6e5df", lw=0.8)
    ax.legend(loc="upper left", bbox_to_anchor=(1.0, 1.0), frameon=False, fontsize=8.5, labelcolor=INK)
    ax.set_title(f"k-means consistency vs k (top-{K})", fontsize=11, color=INK, loc="left")
    fig.tight_layout()
    fig.savefig(FIG / f"step4_k_sweep_K{K}.png", dpi=150, facecolor=SURFACE)


if __name__ == "__main__":
    main()
