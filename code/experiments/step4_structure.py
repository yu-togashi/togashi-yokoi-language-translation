"""Step 4: distance structure of each GW vocabulary (top-K words) — PCA and k-means clusters.

Vectors are normalized as for GW (centre, unit length), so Euclidean distance² = 2·cosine distance
and PCA = classical MDS of the GW cost matrix (up to the mean scaling).

Outputs (per language):
  data/processed/step4/<lang>_K<K>.npz      PCA coords, explained variance, cluster labels, silhouette scan
  analysis/tables/step4_clusters_<lang>_K<K>.md   cluster sizes, frequency ranks, example words
Usage: poetry run python code/experiments/step4_structure.py --langs en es --K 20000 --k 8
"""

from __future__ import annotations

import argparse

import numpy as np
from sklearn.cluster import KMeans
from sklearn.decomposition import PCA
from sklearn.metrics import silhouette_score

from localgw.data import REPO_ROOT, load_vectors
from localgw.preprocess import normalize_embeddings

SEED = 0
OUT_DATA = REPO_ROOT / "data" / "processed" / "step4"
OUT_TAB = REPO_ROOT / "analysis" / "tables"


def analyse(lang: str, K: int, k: int) -> None:
    rng = np.random.default_rng(SEED)
    words, x, _ = load_vectors(lang, K)
    x = normalize_embeddings(x)

    pca = PCA(n_components=50, random_state=SEED).fit(x)
    coords = pca.transform(x)

    # silhouette scan on a fixed subsample (cosine on unit vectors ≡ Euclidean ordering)
    sub = rng.choice(K, size=min(5000, K), replace=False)
    scan = []
    for kk in [2, 4, 6, 8, 10, 12, 16, 20, 30]:
        lab = KMeans(kk, n_init=4, random_state=SEED).fit_predict(x)
        scan.append((kk, silhouette_score(x[sub], lab[sub])))
    km = KMeans(k, n_init=10, random_state=SEED).fit(x)
    labels = km.labels_
    # order clusters by median frequency rank (cluster 0 = most frequent words)
    order = np.argsort([np.median(np.flatnonzero(labels == c)) for c in range(k)])
    remap = np.empty(k, int)
    remap[order] = np.arange(k)
    labels = remap[labels]
    centers = km.cluster_centers_[order]

    OUT_DATA.mkdir(parents=True, exist_ok=True)
    np.savez(OUT_DATA / f"{lang}_K{K}.npz", words=np.array(words), coords=coords[:, :10],
             explained=pca.explained_variance_ratio_, labels=labels,
             scan=np.array(scan))

    lines = [f"# {lang} top-{K}: k-means (k={k}) on normalized vectors\n",
             "Generated by `code/experiments/step4_structure.py`. Clusters ordered by median frequency rank.\n",
             f"PCA explained variance PC1–PC5: "
             + ", ".join(f"{v:.1%}" for v in pca.explained_variance_ratio_[:5])
             + f"; PC1–PC50 total {pca.explained_variance_ratio_.sum():.1%}\n",
             "Silhouette (5000-word subsample): " + ", ".join(f"k={a}: {b:.3f}" for a, b in scan) + "\n",
             "| cluster | size | median rank | most frequent words | words nearest the centre |",
             "|---|---|---|---|---|"]
    for c in range(k):
        idx = np.flatnonzero(labels == c)
        sims = x[idx] @ (centers[c] / np.linalg.norm(centers[c]))
        near = idx[np.argsort(-sims)[:15]]
        lines.append(f"| {c} | {len(idx)} | {int(np.median(idx))} | "
                     f"{' '.join(words[i] for i in idx[:20])} | {' '.join(words[i] for i in near)} |")
    (OUT_TAB / f"step4_clusters_{lang}_K{K}.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--langs", nargs="+", default=["en", "es"])
    ap.add_argument("--K", type=int, default=20000)
    ap.add_argument("--k", type=int, default=8)
    args = ap.parse_args()
    for lang in args.langs:
        analyse(lang, args.K, args.k)


if __name__ == "__main__":
    main()
