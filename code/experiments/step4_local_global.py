"""Step 4: is the EN–ES agreement of distances local or global? (dictionary-matched one-to-one pairs)

Words i, k (EN) and their partners i', k' (ES), restricted to the 11,128 pairs of step4_matched.py.
Distances: vectors normalized as for GW on the full top-K (centre, unit length), cosine distance,
divided by the mean over all matched pairs (so both languages have mean 1). Neighbour ranks are
counted inside the matched set (0 = nearest other word).

  1. |d_s(i,k) − d_t(i',k')| binned by the EN neighbour rank of k from i (and the same with the pairs
     randomly re-assigned = no correspondence)
  2. Spearman correlation of d_s and d_t inside each rank bin
  3. neighbourhood overlap: share of i's EN k-NN whose partners are among i''s ES k-NN, vs k (chance = k/N)
     — overall and per EN k=12 matched cluster (k=10)

Outputs: analysis/tables/step4_local_global_K<K>.md, analysis/figures/step4_local_global_K<K>.png,
         data/processed/step4/local_global_K<K>.npz
Usage: poetry run python code/experiments/step4_local_global.py
"""

from __future__ import annotations

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from scipy.stats import spearmanr  # noqa: E402

from localgw.data import REPO_ROOT, load_vectors  # noqa: E402
from localgw.preprocess import normalize_embeddings  # noqa: E402
from step4_k12_plots import NAMES  # noqa: E402
from step4_plots import DATA, FIG, INK, K, MUTED, SLOT, SURFACE, style  # noqa: E402

SEED = 0
BINS = [(0, 1), (1, 3), (3, 10), (10, 30), (30, 100), (100, 300), (300, 1000), (1000, 3000), (3000, None)]
KNN = [1, 3, 10, 30, 100, 300, 1000, 3000]
OUT_TAB = REPO_ROOT / "analysis" / "tables" / f"step4_local_global_K{K}.md"


def distances(lang, idx):
    x = normalize_embeddings(load_vectors(lang, K)[1])[idx].astype(np.float32)
    d = 1 - x @ x.T
    np.fill_diagonal(d, np.nan)
    d /= np.nanmean(d)
    return d


def ranks(d, chunk=1000):
    """rank[i, j] = position of j in i's neighbour list (0 = nearest); diagonal = n-1."""
    n = len(d)
    r = np.empty((n, n), dtype=np.int16)
    dd = np.where(np.isnan(d), np.inf, d)
    for s in range(0, n, chunk):
        order = np.argsort(dd[s:s + chunk], axis=1)
        rows = np.arange(order.shape[0])[:, None]
        r[s:s + chunk][rows, order] = np.arange(n, dtype=np.int16)[None, :]
    return r


def binned(ds, dt, r_en, rng, n_sample=300_000):
    out = []
    n = len(ds)
    for lo, hi in BINS:
        hi = hi or n - 1  # rank n-1 is the diagonal (self)
        m = (r_en >= lo) & (r_en < hi)
        a, b = ds[m], dt[m]
        diff = np.abs(a - b)
        s = rng.choice(len(a), min(n_sample, len(a)), replace=False)
        out.append(dict(rank=f"{lo + 1}–{hi}", n=int(m.sum()), mean_ds=float(a.mean()), mean_dt=float(b.mean()),
                        mean_absdiff=float(diff.mean()), median_absdiff=float(np.median(diff)),
                        spearman=float(spearmanr(a[s], b[s])[0])))
    return out


def knn_overlap(r_en, r_es):
    return {k: ((r_en < k) & (r_es < k)).sum(1) / k for k in KNN}


def main() -> None:
    rng = np.random.default_rng(SEED)
    m = np.load(DATA / f"k12_K{K}.npz")
    pairs, en_lab = m["pairs"], m["en_matched_labels"]
    n = len(pairs)
    ds, dt = distances("en", pairs[:, 0]), distances("es", pairs[:, 1])
    r_en, r_es = ranks(ds), ranks(dt)
    perm = rng.permutation(n)
    dt_perm = dt[np.ix_(perm, perm)]
    r_es_perm = r_es[np.ix_(perm, perm)]

    stats = binned(ds, dt, r_en, rng)
    stats_rand = binned(ds, dt_perm, r_en, rng)
    ov, ov_rand = knn_overlap(r_en, r_es), knn_overlap(r_en, r_es_perm)
    # also the symmetric view: bins by ES rank
    stats_es = binned(dt, ds, r_es, rng)
    # symmetric conditioning (no regression-to-the-mean bias): bins of the average distance
    iu = np.triu_indices(n, 1)
    pick = rng.choice(len(iu[0]), 5_000_000, replace=False)
    a_s, a_t = ds[iu[0][pick], iu[1][pick]], dt[iu[0][pick], iu[1][pick]]
    avg = (a_s + a_t) / 2
    edges = np.quantile(avg, [0, 0.001, 0.01, 0.05, 0.25, 0.5, 0.75, 0.95, 1])
    sym = []
    for lo, hi in zip(edges[:-1], edges[1:]):
        m_ = (avg >= lo) & (avg <= hi)
        sym.append(dict(lo=lo, hi=hi, n=int(m_.sum()), absdiff=float(np.abs(a_s[m_] - a_t[m_]).mean()),
                        signed=float((a_t[m_] - a_s[m_]).mean()), rand=float(np.abs(
                            a_s[m_] - rng.permutation(a_t)[:m_.sum()]).mean())))

    lines = [f"# Local vs global agreement of EN–ES distances ({n} dictionary-matched pairs, top-{K})", "",
             "Generated by `code/experiments/step4_local_global.py`. Distances normalized to mean 1 in each language;"
             " ranks counted inside the matched set. 'random' = ES partners randomly re-assigned.", "",
             "## |d_EN − d_ES| and Spearman ρ by EN neighbour rank", "",
             "| EN rank of k from i | pairs | mean d_EN | mean d_ES | mean abs diff | random: mean abs diff "
             "| Spearman ρ in bin | random ρ |", "|---|---|---|---|---|---|---|---|"]
    for a, b in zip(stats, stats_rand):
        lines.append(f"| {a['rank']} | {a['n']:,} | {a['mean_ds']:.3f} | {a['mean_dt']:.3f} | {a['mean_absdiff']:.3f} "
                     f"| {b['mean_absdiff']:.3f} | {a['spearman']:.3f} | {b['spearman']:.3f} |")
    lines += ["", "## Same, binned by ES neighbour rank of k' from i'", "",
              "| ES rank | mean d_ES | mean d_EN | mean abs diff | Spearman ρ |", "|---|---|---|---|---|"]
    for a in stats_es:
        lines.append(f"| {a['rank']} | {a['mean_ds']:.3f} | {a['mean_dt']:.3f} | {a['mean_absdiff']:.3f} "
                     f"| {a['spearman']:.3f} |")
    lines += ["", "## Symmetric view: bins of the average distance (d_EN + d_ES)/2 (5M random word pairs)", "",
              "| avg-distance quantile range | avg distance | pairs | mean abs diff | mean (d_ES − d_EN) |",
              "|---|---|---|---|---|"]
    qs = ["0–0.1%", "0.1–1%", "1–5%", "5–25%", "25–50%", "50–75%", "75–95%", "95–100%"]
    for q, b in zip(qs, sym):
        lines.append(f"| {q} | {b['lo']:.2f}–{b['hi']:.2f} | {b['n']:,} | {b['absdiff']:.3f} | {b['signed']:+.3f} |")
    lines += ["", "## Neighbourhood overlap (share of EN k-NN whose partners are ES k-NN)", "",
              "| k | overlap | random | chance k/N |", "|---|---|---|---|"]
    for k in KNN:
        lines.append(f"| {k} | {ov[k].mean():.3f} | {ov_rand[k].mean():.3f} | {k / (n - 1):.4f} |")
    lines += ["", "## Overlap at k=10 per EN k=12 matched cluster", "", "| EN cluster | words | overlap@10 |",
              "|---|---|---|"]
    per = []
    for c in range(12):
        sel = en_lab == c
        per.append(ov[10][sel].mean())
        lines.append(f"| {NAMES['en', 'matched'][c]} | {sel.sum()} | {per[-1]:.3f} |")
    OUT_TAB.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    np.savez(DATA / f"local_global_K{K}.npz", overlap10=ov[10], en_labels=en_lab)

    # figure
    fig, axes = plt.subplots(2, 2, figsize=(15, 11), facecolor=SURFACE)
    axes = axes.flat
    x = np.arange(len(BINS))
    labels = [s["rank"] for s in stats]
    ax = axes[0]
    style(ax)
    ax.plot(x, [s["mean_absdiff"] for s in stats], color=SLOT[0], lw=2, marker="o", ms=7, label="dictionary pairs")
    ax.plot(x, [s["mean_absdiff"] for s in stats_rand], color=MUTED, lw=2, marker="o", ms=7, ls="--",
            label="random re-assignment")
    ax.set_xticks(x, labels, rotation=45, fontsize=8)
    ax.set_xlabel("EN neighbour rank of k from i", color=MUTED, fontsize=9)
    ax.set_ylabel("mean |d_EN(i,k) − d_ES(i',k')|  (mean distance = 1)", color=MUTED, fontsize=9)
    ax.set_title("(a) distance mismatch by neighbour rank", fontsize=11, color=INK, loc="left")
    ax.legend(frameon=False, fontsize=8.5, labelcolor=INK)
    ax.set_ylim(bottom=0)

    ax = axes[1]
    style(ax)
    ax.plot(x, [s["spearman"] for s in stats], color=SLOT[0], lw=2, marker="o", ms=7, label="dictionary pairs")
    ax.plot(x, [s["spearman"] for s in stats_rand], color=MUTED, lw=2, marker="o", ms=7, ls="--",
            label="random re-assignment")
    ax.axhline(0, color=MUTED, lw=0.8)
    ax.set_xticks(x, labels, rotation=45, fontsize=8)
    ax.set_xlabel("EN neighbour rank of k from i", color=MUTED, fontsize=9)
    ax.set_ylabel("Spearman ρ(d_EN, d_ES) within the bin", color=MUTED, fontsize=9)
    ax.set_title("(b) agreement of distances within each rank bin", fontsize=11, color=INK, loc="left")
    ax.legend(frameon=False, fontsize=8.5, labelcolor=INK)

    ax = axes[2]
    style(ax)
    ax.plot(KNN, [ov[k].mean() for k in KNN], color=SLOT[0], lw=2, marker="o", ms=7, label="dictionary pairs")
    ax.plot(KNN, [ov_rand[k].mean() for k in KNN], color=MUTED, lw=2, marker="o", ms=7, ls="--",
            label="random re-assignment")
    ax.plot(KNN, [k / (n - 1) for k in KNN], color=MUTED, lw=1, ls=":", label="chance k/N")
    ax.set_xscale("log")
    ax.set_xlabel("neighbourhood size k", color=MUTED, fontsize=9)
    ax.set_ylabel("share of EN k-NN that are also ES k-NN", color=MUTED, fontsize=9)
    ax.set_title("(c) neighbourhood overlap", fontsize=11, color=INK, loc="left")
    ax.legend(frameon=False, fontsize=8.5, labelcolor=INK)
    ax.set_ylim(0, 1)

    ax = axes[3]
    style(ax)
    order = np.argsort(per)
    ax.barh(np.arange(12), np.array(per)[order], color=SLOT[0], height=0.7)
    ax.axvline(ov[10].mean(), color=MUTED, lw=1, ls="--")
    ax.text(ov[10].mean() + 0.005, -0.9, f"all words {ov[10].mean():.2f}", color=MUTED, fontsize=8, ha="left")
    ax.set_yticks(np.arange(12), [NAMES["en", "matched"][c] for c in order], fontsize=8.5, color=INK)
    for yy, v in enumerate(np.array(per)[order]):
        ax.text(v + 0.005, yy, f"{v:.2f}", va="center", fontsize=8, color=INK)
    ax.set_xlabel("neighbourhood overlap at k=10 (chance 0.001)", color=MUTED, fontsize=9)
    ax.set_title("(d) overlap@10 by EN cluster (k=12, matched)", fontsize=11, color=INK, loc="left")
    ax.set_xlim(0, 0.7)
    fig.suptitle(f"EN–ES distance agreement, local vs global ({n} dictionary-matched pairs, top-{K})",
                 fontsize=12, color=INK, x=0.01, ha="left")
    fig.tight_layout()
    fig.savefig(FIG / f"step4_local_global_K{K}.png", dpi=150, facecolor=SURFACE)


if __name__ == "__main__":
    main()
