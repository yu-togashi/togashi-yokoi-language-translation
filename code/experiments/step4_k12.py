"""Step 4, k=12: k-means on the full top-K vocabularies and on the dictionary-matched words.

Clusters are ordered by median frequency rank within each clustering. Saves labels for plotting
(step4_k12_plots.py) and per-cluster word tables for naming.

Outputs: data/processed/step4/k12_K<K>.npz, analysis/tables/step4_k12_clusters_K<K>.md
Usage: poetry run python code/experiments/step4_k12.py
"""

from __future__ import annotations

import numpy as np
from sklearn.cluster import KMeans
from sklearn.decomposition import PCA

from localgw.data import REPO_ROOT, load_vectors
from localgw.preprocess import normalize_embeddings
from step4_plots import DATA, K

k, SEED = 12, 0
OUT_TAB = REPO_ROOT / "analysis" / "tables" / f"step4_k12_clusters_K{K}.md"


def cluster(x, rank):
    km = KMeans(k, n_init=10, random_state=SEED).fit(x)
    order = np.argsort([np.median(rank[km.labels_ == c]) for c in range(k)])
    remap = np.empty(k, int)
    remap[order] = np.arange(k)
    return remap[km.labels_], km.cluster_centers_[order]


def table(title, words, x, labels, centers, rank):
    lines = [f"## {title}", "", "| cluster | size | median rank | most frequent words | words nearest the centre |",
             "|---|---|---|---|---|"]
    for c in range(k):
        idx = np.flatnonzero(labels == c)
        near = idx[np.argsort(-(x[idx] @ (centers[c] / np.linalg.norm(centers[c]))))[:15]]
        lines.append(f"| {c} | {len(idx)} | {int(np.median(rank[idx]))} | {' '.join(words[idx[:20]])} "
                     f"| {' '.join(words[near])} |")
    return lines + [""]


def main() -> None:
    pairs = np.load(DATA / f"matched_K{K}.npz")["pairs"]
    out, lines = {"pairs": pairs}, [f"# k-means k={k} on top-{K} (full) and on matched words", "",
                                    "Generated by `code/experiments/step4_k12.py`.", ""]
    for li, lang in enumerate(["en", "es"]):
        words, x, _ = load_vectors(lang, K)
        words = np.array(words)
        xf = normalize_embeddings(x)
        rank = np.arange(K)
        lf, cf = cluster(xf, rank)
        idx = pairs[:, li]
        xm = normalize_embeddings(x[idx])
        lm, cm = cluster(xm, idx)
        out[f"{lang}_full_labels"], out[f"{lang}_matched_labels"] = lf, lm
        out[f"{lang}_full_coords"] = PCA(2, random_state=SEED).fit_transform(xf)
        out[f"{lang}_matched_coords"] = PCA(2, random_state=SEED).fit_transform(xm)
        out[f"{lang}_words"] = words
        lines += table(f"{lang} full ({K} words)", words, xf, lf, cf, rank)
        lines += table(f"{lang} matched ({len(idx)} words)", words[idx], xm, lm, cm, idx)
    np.savez(DATA / f"k12_K{K}.npz", **out)
    OUT_TAB.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
